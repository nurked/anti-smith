#!/usr/bin/env node
/**
 * Regenerates docs/plugin-catalog.md from plugin metadata, so the catalog never
 * drifts from the code. Usage: node tools/gen-catalog.mjs
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { discoverPlugins } from './lib/discover-plugins.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const plugins = [];
for (const info of await discoverPlugins(root)) {
  plugins.push({ ...(await import(pathToFileURL(info.entry).href)).default, folder: path.relative(root, info.dir) });
}

const lines = [
  '# Plugin catalog',
  '',
  '_Generated by `node tools/gen-catalog.mjs` from plugin metadata. Do not edit by hand._',
  '',
  '| Plugin | Kind | Weight | Phase | Noisy | What it does |',
  '| --- | --- | --- | --- | --- | --- |',
  ...plugins.map(
    (p) => `| [\`${p.id}\`](../${p.folder}/) | ${p.kind} | ${p.weight ?? '—'} | ${p.phase ?? '—'} | ${p.noisy ? 'yes' : ''} | ${p.description} |`,
  ),
  '',
  '## Known limitations',
  '',
];
for (const p of plugins.filter((p) => p.limitations?.length)) {
  lines.push(`### ${p.title} (\`${p.id}\`)`, '', ...p.limitations.map((l) => `- ${l}`), '');
}

await writeFile(path.join(root, 'docs', 'plugin-catalog.md'), lines.join('\n'));
console.log(`Wrote docs/plugin-catalog.md (${plugins.length} plugins)`);
